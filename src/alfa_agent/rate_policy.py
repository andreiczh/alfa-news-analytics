def rate_pause_memo(ledger, sources, request, snapshot):
    """Return None outside verified coverage; never infer an event from a headline lead."""
    if not re.search(r"ставк|фондир|оборотн\w*\s+капитал|денежн\w*\s+рынок", request["question"], re.I):
        return None
    as_of = datetime.fromisoformat(request["as_of"].replace("Z", "+00:00"))
    selected = request.get("news_item_id")
    eligible = []
    for source in sources:
        host = (urlsplit(source.get("url") or "").hostname or "").lower()
        if source["kind"] != "public_page" or not (host == "cbr.ru" or host.endswith(".cbr.ru")):
            continue
        if selected and source["source_id"] != selected:
            continue
        if source.get("date_source") == "search_feed":
            continue
        title = source.get("title", "")
        if not re.search(
            r"приня\w*\s+решени\w*[^.!?]{0,70}сохран\w*[^.!?]{0,60}ключев\w*\s+ставк", title, re.I
        ) or re.search(r"год\s+назад|историч|ретроспектив|архив", title, re.I):
            continue
        try:
            stamp = datetime.fromisoformat(source["published_at"].replace("Z", "+00:00"))
            age = (as_of - stamp).total_seconds()
        except (KeyError, ValueError, TypeError, AttributeError):
            continue
        if 0 <= age <= 7 * 86400 and re.search(
            r"сохран\w*[^.!?]{0,70}ключев\w*\s+ставк", source.get("text", ""), re.I
        ):
            eligible.append(source)
    if not eligible:
        return None
    event_ids = {s["source_id"] for s in eligible}
    options = source_message_options(ledger)
    event = next(
        (
            o
            for o in options
            if any(a["anchor_id"] == o["anchor_id"] and a["source_id"] in event_ids for a in ledger)
            and o["kind"] == "source_fact"
            and any(o["text"] in s.get("text", "") for s in eligible)
            and re.search(r"сохран\w*[^.!?]{0,70}ключев\w*\s+ставк", o["text"], re.I)
        ),
        None,
    )
    bank = next(
        (
            o
            for o in options
            if any(
                a["anchor_id"] == o["anchor_id"] and a["kind"] in {"bank_claim", "bank_excerpt"}
                for a in ledger
            )
        ),
        None,
    )
    if not event or not bank:
        return None
    by_context = {
        a.get("context_key"): a for a in ledger if a["kind"] == "company_evidence" and a.get("context_key")
    }
    context = (
        by_context.get("priorities")
        or by_context.get("goals")
        or next((a for a in ledger if a["kind"] == "company_evidence"), None)
    )
    if not context:
        return None
    goal = by_context.get("goals") or context
    industry = by_context.get("industry") or context
    watched = by_context.get("tracked_competitors") or context
    role = request.get("role") or "cfo"
    actions = (BANK_ACTIONS if request["bank_company"] else CORPORATE_ACTIONS).get(
        role, CORPORATE_ACTIONS["cfo"]
    )
    declared = " ".join(f.get("value", "") for f in snapshot.get("context", {}).get("fields", {}).values())
    declared_industry = snapshot.get("context", {}).get("fields", {}).get("industry", {}).get("value", "")
    policy = planning_policy(request["as_of"], request.get("planning_days", 30))

    def refs(*items):
        return list(dict.fromkeys(i["anchor_id"] for i in items))[:3]

    def point(text, anchors=None, condition=None):
        return {
            "kind": "interpretation",
            "text": text,
            "anchor_ids": anchors or refs(event, bank, context),
            "condition": condition
            or "Условный механизм; фактическая экспозиция, договоры и финансовый эффект компании требуют внутренних данных.",
        }

    situation = [
        {
            "kind": event["kind"],
            "text": event["text"],
            "anchor_ids": [event["anchor_id"]],
            "condition": "Решение регулятора на дату публикации. Оно не устанавливает будущую траекторию ставки на весь плановый период.",
        },
        {
            "kind": bank["kind"],
            "text": bank["text"],
            "anchor_ids": [bank["anchor_id"]],
            "condition": (
                "Материал банка с указанной датой публикации. "
                if bank.get("published_at")
                else "Дата публикации материала банка не установлена. "
            )
            + "Прогноз или оценка не становятся текущим исходом; механизм рассматривается условно.",
        },
    ]
    situation.append(
        {
            "kind": "source_assessment",
            "text": context["quote"],
            "anchor_ids": [context["anchor_id"]],
            "condition": "Сведения из доступного профиля компании; происхождение показано в основании, независимая проверка не проводилась.",
        }
    )
    bank_company = request["bank_company"]
    mechanism = (
        "Процентный результат банка зависит от ставок и сроков переоценки обеих сторон баланса. Без гэпа переоценки, депозитной беты и структуры активов и обязательств знак чистого эффекта не установлен."
        if bank_company
        else "Рыночные ставки влияют на новые договоры и рефинансирование; плавающие условия меняются по договорной формуле и календарю. Действующий фиксированный долг автоматически не переоценивается."
    )
    base_outcome = "Если ключевая ставка и рыночные спреды не меняются, проверить действующие условия и план новых договоров. Потребность в средствах и фактический финансовый результат компании этим условием не определяются."
    alternative = "Если рыночный спред вырастет, новое фондирование может подорожать даже при неизменной ключевой ставке; проверить чувствительность новых договоров и денежного плана к отдельному росту спреда."
    scenarios = []
    for variant, title, outcome, assumptions in [
        (
            "base",
            "Неизменные внешние условия",
            base_outcome,
            [
                "Ключевая ставка и рыночные спреды условно не меняются в выбранном окне.",
                "Условия и график действующих договоров проверяются отдельно.",
            ],
        ),
        (
            "alternative",
            "Рост рыночного спреда",
            alternative,
            [
                "Спред денежного рынка или новых договоров растёт по отдельной причине.",
                "У компании есть потребность в новых договорах или договорной переоценке; её наличие нужно проверить.",
            ],
        ),
    ]:
        scenarios.append(
            {
                "variant": variant,
                "title": title,
                "outcome": outcome,
                "horizon": policy["horizon"],
                "mechanism": "Высокий уровень ставки отличается от нового роста стоимости. Если спред увеличивается, стоимость новых договоров может вырасти; фиксированные действующие условия этим автоматически не меняются.",
                "assumptions": assumptions,
                "change_signals": [
                    "Изменение спреда денежных ставок к ключевой ставке.",
                    "Фактические условия новых предложений и договорные даты переоценки.",
                    "Отклонение фактических поступлений и платежей от внутреннего плана.",
                ],
                "anchor_ids": refs(event, bank),
                "confidence_reason": "Событие связано с прочитанным первоисточником регулятора; сценарии задают условия проверки, их вероятности и чистый эффект не рассчитаны.",
            }
        )
    impact = [
        point(
            "Проверки нужно связать с указанными вами целями и приоритетами. Рыночная публикация не подтверждает фактическую чувствительность спроса, денежных потоков или договоров именно этой компании.",
            refs(event, goal, industry),
        )
    ]
    if bank_company and re.search(r"мал\w*\s+бизнес|\bМСП\b|\bSME\b", declared, re.I):
        impact.append(
            point(
                "Для указанной цели развития малого бизнеса проверить условия продуктов, конверсию и спрос по клиентским сегментам. Если условия предложений меняются, реакция клиентов может отличаться; сама пауза по ставке не доказывает изменения спроса.",
                refs(event, goal, context),
            )
        )
    elif not bank_company and re.search(r"рознич|ритейл|ретейл|магазин", declared_industry, re.I):
        impact.append(
            point(
                "Для заявленного розничного бизнеса сравнить спрос, ассортимент, закупочные и отпускные цены по категориям. Если чувствительность покупателей к цене меняется, проверить ценовое позиционирование и оборачиваемость; фактическая реакция по данным компании не установлена.",
                refs(event, goal, industry),
            )
        )
    elif not bank_company and re.search(r"металлург|производств|машиностро", declared_industry, re.I):
        impact.append(
            point(
                "Для указанного производственного контекста сопоставить заказы, сроки оплаты и условия закупок с графиком исполнения. Если денежный цикл удлиняется, возможна дополнительная потребность в средствах; её наличие и размер требуют внутреннего плана.",
                refs(event, goal, industry),
            )
        )
    titles = {
        "cfo": "финансовый план",
        "treasurer": "проверка ликвидности",
        "ceo": "управленческие приоритеты",
        "coo": "денежный цикл операций",
        "cco": "коммерческие условия",
        "cmo": "спрос и ценовое позиционирование",
    }
    return DecisionNarrative.model_validate(
        {
            "title": "Ставка без изменений: " + titles.get(role, "проверка управленческого плана"),
            "main_conclusion": point(
                "Решение описывает ставку на дату события. Для планирования важно "
                + actions[0]
                + ". Будущие решения регулятора и чистый финансовый эффект компании не установлены."
            ),
            "situation": situation,
            "drivers": [
                point(mechanism),
                point(
                    "Сохранение ставки само по себе не создаёт нового ценового шока. Если отдельный рыночный спред увеличится, стоимость новых договоров может вырасти; это другой условный механизм."
                ),
            ],
            "company_impact": impact,
            "risks": [
                point(
                    "Если условия новых договоров ухудшатся или поступления будут отставать от платежей, возможна дополнительная потребность в средствах. Её размер и наличие кассового разрыва требуют денежного плана компании."
                )
            ],
            "opportunities": [],
            "recommendations": [
                point(actions[1], refs(event, bank, goal)),
                point(actions[2], refs(event, context, watched)),
            ],
            "forecast_status": "conditional_scenarios",
            "forecast_limit": "Это проверка условных механизмов. В этом исследовании не выполнялся расчёт по полной денежной, операционной или балансовой модели компании; траектория ставки, вероятность сценариев, прибыль и достаточность ликвидности не определяются.",
            "scenarios": scenarios,
            "context_keys": [],
        }
    )
