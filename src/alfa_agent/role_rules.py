def catalogue(profile):
    features = {f.name: f for f in profile.features if f.status not in {"missing", "conflicting"}}
    fixed = features.get("rate_type") and features["rate_type"].text_value == "fixed"
    floating = features.get("rate_type") and features["rate_type"].text_value == "floating"
    deposit = bool(
        features.get("has_deposit")
        and features["has_deposit"].boolean_value
        and not (features.get("has_loan") and features["has_loan"].boolean_value)
    )
    cfo = (
        "fixed_budget"
        if fixed
        else "floating_budget"
        if floating and "floating_debt_rub" in features
        else "floating_amount_unknown"
        if floating
        else "deposit_budget"
        if deposit
        else "debt_structure_unknown"
    )
    keys = [
        cfo,
        "fixed_contracts"
        if fixed
        else "floating_contracts"
        if floating
        else "deposit_contracts"
        if deposit
        else "treasury_unknown",
        "capex_funding" if "capex_planned_rub" in features else "strategy_context",
        "inventory_funding" if "inventory_days" in features else "operations_context",
        "receivables_funding"
        if {"receivables_days", "credit_sales_share"} <= features.keys()
        else "commercial_context",
    ]
    return {
        RULES[key][0]: {
            "mechanism": key,
            "action_id": key,
            "feature_ids": [features[n].feature_id for n in RULES[key][1] if n in features],
        }
        for key in keys
    }


def render_rule(role, profile):
    selected = catalogue(profile)[role.role]
    if role.mechanism != selected["mechanism"] or role.action_id != selected["action_id"]:
        raise ValueError("role_rule_does_not_match_profile")
    data = RULES[role.mechanism]
    return {
        "explanation": data[2],
        "conditions": data[3],
        "action_title": data[4],
        "required_data": data[5],
        "feature_ids": selected["feature_ids"],
    }
